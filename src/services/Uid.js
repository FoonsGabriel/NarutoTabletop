/**
 * Id único no formato de UUID.
 * crypto.randomUUID() só existe em HTTPS (no celular pelo IP da rede, http://192.168…, ele não existe).
 * crypto.getRandomValues funciona nos dois.
 */
export function uid() {
  if (typeof crypto !== 'undefined' && crypto.randomUUID && window.isSecureContext) return crypto.randomUUID();
  const bytes = new Uint8Array(16);
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) crypto.getRandomValues(bytes);
  else for (let i = 0; i < 16; i += 1) bytes[i] = Math.floor(Math.random() * 256);
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = [...bytes].map((b) => b.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
